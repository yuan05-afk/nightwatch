"""
Builds submission/NIGHTWATCH-DataNova2026-submission.zip for the Devpost "Additional info" upload (35 MB limit):
presentation, documentation, evaluation reports and a source snapshot taken from git (committed files only).
    python submission/build_zip.py
"""
import json
import shutil
import subprocess
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
B = ROOT / "submission" / "_bundle"
OUT = ROOT / "submission" / "NIGHTWATCH-DataNova2026-submission.zip"
LIMIT = 35 * 1024 * 1024

shutil.rmtree(B, ignore_errors=True)
for d in ("01-presentation", "02-documentation", "03-evaluation", "04-source-code"):
    (B / d).mkdir(parents=True)

for f in ("NIGHTWATCH-DataNova2026.pptx", "NIGHTWATCH-DataNova2026.pdf"):
    shutil.copy2(ROOT / "deck" / f, B / "01-presentation" / f)

shutil.copy2(ROOT / "README.md", B / "02-documentation" / "README.md")
shutil.copy2(ROOT / "docs" / "METHOD.md", B / "02-documentation" / "METHOD.md")
shutil.copy2(ROOT / "docs" / "RESEARCH.md", B / "02-documentation" / "RESEARCH.md")
shutil.copy2(ROOT / "video" / "README.md", B / "02-documentation" / "DEMO-VIDEO.md")
shutil.copytree(ROOT / "docs" / "screenshots", B / "02-documentation" / "screenshots")

DESCRIBE = {
    "final.json": "Final model on the held-out test split: per-class metrics, verdict mix, conformal coverage, base-rate table",
    "ablation.json": "Imbalance strategies (none, class-balanced, SMOTE) scored on calibration and test; selection rule",
    "illusion.json": "The same model on a shuffled split vs the time-ordered split",
    "zero_day.json": "Leave-one-family-out test: each attack family removed from training, then scored",
    "operating_curve.json": "False-alert budget sweep for the normal class (trade-off curve)",
    "no_port.json": "Ablation without destination port and protocol",
    "triage.json": "Prioritization on five replayed days: incidents reached per review budget vs oldest-first and confidence-only",
    "anomaly_ablation.json": "Isolation Forest backstop: what it flags on its own",
}
lines = ["# Evaluation reports", "", "Generated by `uv run python -m nightwatch_ml.pipeline` (see 02-documentation/METHOD.md). Every number in the",
         "presentation, README, Method page and demo video comes from these files.", ""]
for f in sorted((ROOT / "ml" / "reports").glob("*.json")):
    shutil.copy2(f, B / "03-evaluation" / f.name)
    lines.append(f"- `{f.name}`: {DESCRIBE.get(f.name, '')}")
(B / "03-evaluation" / "REPORTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

head = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
subprocess.check_call(["git", "archive", "--format=zip", f"--prefix=nightwatch/", "-o", str(B / "04-source-code" / f"nightwatch-source-{head}.zip"), "HEAD"], cwd=ROOT)

final = json.loads((ROOT / "ml" / "reports" / "final.json").read_text())
v = final["verdicts"]
(B / "README-FIRST.md").write_text(f"""# NIGHTWATCH: Your Night-Shift Security Analyst

DataNova 2026 Global Data-thon, Cybersecurity and Fraud Detection, DN-CY-01.

- Live demo: https://nightwatch-olive.vercel.app (press "Use the judge demo account" on the sign-in page)
- Source code: https://github.com/yuan05-afk/nightwatch (snapshot {head} in 04-source-code)
- Method and results: https://nightwatch-olive.vercel.app/method

Held-out test split: {v['attack_flagged'] * 100:.2f}% of attack flows raised an alert, {v['benign_alert_rate'] * 100:.2f}% of normal flows raised a
false alert, macro-F1 over attack classes {final['classifier']['macro_f1_attacks']:.3f}.

| Folder | Contents |
| --- | --- |
| 01-presentation | The deck (PPTX and PDF) |
| 02-documentation | README, method, research sources, demo-video production notes, screenshots |
| 03-evaluation | Raw evaluation reports (JSON) with an index |
| 04-source-code | Source snapshot from git: ML pipeline, web app, deck generator, video sources |

The dataset itself is not included (third-party, 328 MB); RESEARCH.md links the download.
""", encoding="utf-8")

OUT.unlink(missing_ok=True)
with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for p in sorted(B.rglob("*")):
        if p.is_file():
            z.write(p, p.relative_to(B))
size = OUT.stat().st_size
print(f"{OUT.name}: {size / 1024 / 1024:.1f} MB ({'OK' if size < LIMIT else 'OVER THE 35 MB LIMIT'})")
shutil.rmtree(B)
