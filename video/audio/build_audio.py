"""
NIGHTWATCH audio bed: ElevenLabs narration (single take) + procedurally composed score + SFX, ducked and mixed.
Same arrangement and mix as the GroundTruth demo (../../audio/build_audio_v3.py).
Cue times come from src/timeline.json (generated by audio/timeline.py).
Outputs to public/audio/: vo_track.wav, music.wav, sfx.wav, mix.wav
The narration is cut at silent gap boundaries (TL2["gaps"]) and re-placed with extra silence so the picture can breathe.
"""
import json
import subprocess
import sys
from pathlib import Path

import numpy as np
from scipy.io import wavfile

sys.path.insert(0, str(Path(__file__).resolve().parent))
import synth as B  # noqa: E402  (synth helpers shared with the GroundTruth demo)

ROOT = B.ROOT
OUT = B.AUDIO
TL2 = json.loads((ROOT / "src" / "timeline.json").read_text())
B.configure(TL2["duration"])
SR, N, DUR = B.SR, B.N, B.DUR
M = TL2["music"]
CLOSE = M["close"]
rng = np.random.default_rng(11)


def build_vo():
    src = OUT / "vo.mp3"
    wav = OUT / "vo_mono.wav"
    subprocess.check_call(["ffmpeg", "-y", "-v", "error", "-i", str(src), "-ac", "1", "-ar", str(SR), str(wav)])
    sr, data = wavfile.read(wav)
    x = data.astype(np.float64) / 32768.0
    buf = B.silence()
    bounds = [0.0] + [g[0] for g in TL2["gaps"]] + [len(x) / SR + 1.0]
    cum = 0.0
    for i in range(len(bounds) - 1):
        a, b = bounds[i], bounds[i + 1]
        if i > 0:
            cum += TL2["gaps"][i - 1][1]
        seg = x[int(a * SR) : int(b * SR)].copy()
        fade = int(0.006 * SR)
        seg[:fade] *= np.linspace(0, 1, fade)
        seg[-fade:] *= np.linspace(1, 0, fade)
        B.place(buf, seg, a + cum + TL2["voOffset"])
    raw = OUT / "vo_raw.wav"
    wavfile.write(raw, SR, (np.clip(buf, -1, 1) * 32767).astype(np.int16))
    out = OUT / "vo_track.wav"
    subprocess.check_call(
        [
            "ffmpeg", "-y", "-v", "error", "-i", str(raw), "-af",
            "highpass=f=75,equalizer=f=3000:t=q:w=1.2:g=1.5,acompressor=threshold=-20dB:ratio=2.5:attack=10:release=150:makeup=2,loudnorm=I=-16:TP=-1.5:LRA=7",
            "-ar", str(SR), str(out),
        ]
    )
    sr, data = wavfile.read(out)
    y = data.astype(np.float64) / 32768.0
    if y.ndim == 1:
        y = np.stack([y, y], axis=1)
    if len(y) < N:
        y = np.vstack([y, np.zeros((N - len(y), 2))])
    return y[:N]


def build_music():
    pads, bass, plucks, drums, top = (B.silence() for _ in range(5))
    BEAT, BAR = B.BEAT, B.BAR
    t, idx, segs = 0.0, 0, []
    while t < CLOSE - 0.01:
        segs.append((t, B.PROG[idx % len(B.PROG)]))
        t += BAR * 2
        idx += 1
    segs.append((CLOSE, "D"))
    ends = [s[0] for s in segs[1:]] + [DUR + 3]
    s = M["sections"]
    pad_env = B.smooth_ramp([0, s[1], s[2], s[3], s[4], s[5], s[6]], [0.5, 0.72, 0.55, 0.95, 1.0, 1.1, 0.8])
    g0, g1 = M["groove"]
    c0, c1 = M["clock"]

    for (start, name), end in zip(segs, ends):
        b, pm, pk = B.CHORDS[name]
        seg_len = min(end - start + 1.6, DUR + 3 - start)
        for m in pm:
            B.place(pads, B.pad_note(B.mtof(m), seg_len), start, pan=rng.uniform(-0.4, 0.4), gain=0.07)
        B.place(pads, B.pad_note(B.mtof(b), seg_len), start, gain=0.12)
        if s[3] <= start < CLOSE - 0.1 or (start < s[3] <= end and end > s[3] + 2):
            beats = int((end - start) / BEAT)
            for k in range(0, beats, 2):
                tn = start + k * BEAT
                if tn < s[3] - 0.01 or tn >= CLOSE - 0.2:
                    continue
                bt = B.tt(BEAT * 1.9)
                sig = np.sin(2 * np.pi * B.mtof(b) * bt) + 0.25 * np.sin(2 * np.pi * B.mtof(b) * 2 * bt)
                sig *= np.exp(-bt * 2.2) * 0.5
                sig[:40] *= np.linspace(0, 1, 40)
                B.place(bass, sig, tn, gain=0.55)
        # sparse supporting plucks while the numbers climb
        if s[1] <= start < s[2] + BAR:
            for k in range(int((end - start) / BEAT)):
                tn = start + k * BEAT
                if s[1] <= tn < s[2]:
                    B.place(plucks, B.pluck(B.mtof(pk[(k * 2) % 4])), tn, pan=-0.2 + 0.1 * (k % 4), gain=0.07)
        # arpeggio from the product reveal to the close
        if start < CLOSE and end > s[3]:
            pat = [0, 2, 1, 3, 2, 1, 3, 2]
            n8 = int((end - start) / (BEAT / 2))
            for k in range(n8):
                tn = start + k * BEAT / 2
                if tn < s[3] + 0.4 or tn >= CLOSE - 0.1 or tn >= DUR:
                    continue
                vel = 0.5 if k % 4 else 0.8
                B.place(plucks, B.pluck(B.mtof(pk[pat[k % 8] % 4])), tn, pan=-0.3 + 0.6 * ((k % 8) / 7), gain=0.11 * vel)

    for k in range(int(DUR / BEAT)):
        tn = k * BEAT
        if tn < 0.3 or tn >= CLOSE - 0.1:
            continue
        if tn < s[1]:
            if k % 2 == 0:
                B.place(drums, B.kick(0.45), tn, gain=0.2 * (0.5 + 0.5 * tn / s[1]))
        elif tn < s[2]:
            B.place(drums, B.kick(0.45), tn, gain=0.14 + 0.1 * (tn - s[1]) / (s[2] - s[1]))
            if k % 2:
                B.place(drums, B.hat(0.05), tn + BEAT / 2, pan=0.2, gain=0.05)
        elif c0 <= tn < c1:
            B.place(drums, B.tick_clock(), tn, pan=0.25, gain=0.1)
        elif tn < g0:
            if k % 2 == 0:
                B.place(drums, B.kick(0.45), tn, gain=0.2)
        elif tn < g1:
            B.place(drums, B.kick(0.5), tn, gain=0.34 if k % 4 else 0.4)
            B.place(drums, B.hat(), tn + BEAT / 2, pan=0.2, gain=0.1)
            if k % 2 == 1:
                B.place(drums, B.hat(0.05), tn, pan=-0.2, gain=0.05)

    for t_end, ln in M["risers"]:
        n = rng.standard_normal(int(SR * ln))
        tt_ = np.linspace(0, 1, len(n))
        sweep = np.zeros_like(n)
        for i0 in range(0, len(n), 2048):
            fc = 300 + 5200 * (i0 / len(n)) ** 2
            seg = n[i0 : i0 + 2048]
            sweep[i0 : i0 + 2048] = B.bp(seg, fc * 0.6, fc * 1.4, 1) if len(seg) > 30 else seg
        sweep *= tt_**2.2
        B.place(top, sweep, max(0, t_end - ln), gain=0.06)

    for k, m in enumerate([74, 78, 81, 86, 81, 78, 74, 78]):
        B.place(top, B.bell(B.mtof(m), 3.2), CLOSE + 0.45 + k * BEAT / 2, pan=-0.4 + 0.12 * k, gain=0.07)
    B.place(top, B.bell(B.mtof(62), 5.0), CLOSE + 0.3, gain=0.1)
    B.place(top, B.bell(B.mtof(50), 6.0), CLOSE + 0.3, gain=0.12)

    pads *= pad_env[:, None]
    wet = B.reverb(pads + plucks + top, wet=0.55, length=2.8)
    mix = wet + bass + drums
    fade_in = np.minimum(1, np.arange(N) / (SR * 0.5))
    fade_out = np.minimum(1, np.maximum(0, (DUR - np.arange(N) / SR)) / 2.4)
    mix *= (fade_in * fade_out)[:, None]
    mix = B.hp(mix, 28, 1)
    return mix / np.max(np.abs(mix)) * 0.8


def sfx_swish():
    x = B.sfx_whoosh(0.32)
    return B.hp(x, 900) * 0.7


def build_sfx():
    buf = B.silence()
    for c in TL2["sfx"]:
        typ, t, g, p = c["type"], c["t"], c.get("gain", 0.5), c.get("pitch", 1.0)
        x = {
            "click": B.sfx_click, "whoosh": B.sfx_whoosh, "boom": B.sfx_boom, "thud": B.sfx_thud,
            "ping": lambda: B.sfx_ping(p), "pop": lambda: B.sfx_pop(p), "swish": sfx_swish,
            "tick": lambda: B.sfx_tick(1.1),
        }[typ]()
        B.place(buf, x, t, gain=g * 0.5)
    for run in TL2["tickRuns"]:
        for t, p in zip(np.linspace(run["from"], run["to"], run["count"]), np.linspace(run["pitch"][0], run["pitch"][1], run["count"])):
            B.place(buf, B.sfx_tick(p), t, pan=0.1, gain=run["gain"] * 0.35)
    return B.reverb(buf, wet=0.18, length=1.2)


def to_wav(path, x):
    wavfile.write(path, SR, (np.clip(x, -1, 1) * 32767).astype(np.int16))


def main():
    print("VO ...")
    vo = build_vo()
    print("music ...")
    music = build_music()
    print("sfx ...")
    sfx = build_sfx()
    gate = B.speech_gate(vo)
    music_gain = (0.8 - 0.48 * gate)[:, None]
    sfx_n = sfx / (np.max(np.abs(sfx)) + 1e-9) * 0.5
    to_wav(OUT / "music.wav", music)
    to_wav(OUT / "sfx.wav", sfx_n)
    mix = vo * 0.95 + music * music_gain + sfx_n * 0.6
    mix = np.tanh(mix * 1.05) / np.tanh(1.05)
    mix *= 0.84
    to_wav(OUT / "mix.wav", mix)
    print("peak", round(float(np.max(np.abs(mix))), 3))


if __name__ == "__main__":
    main()
