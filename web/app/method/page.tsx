function label(s: string) {
  return { none: "No reweighting", balanced: "Balanced class weights", smote: "SMOTE oversampling" }[s] ?? s;
}

function H2({ children, id }: { children: ReactNode; id?: string }) {
  return <h2 id={id} className="mt-20 scroll-mt-28 font-display text-[clamp(1.7rem,3vw,2.3rem)] text-ink">{children}</h2>;
}

function P({ children }: { children: ReactNode }) {
  return <p className="mt-4 text-[0.95rem] leading-[1.7] text-ink-soft">{children}</p>;
}

function Callout({ children }: { children: ReactNode }) {
  return <p className="mt-6 rounded-2xl border border-unknown/30 bg-unknown/[0.06] p-5 text-[0.92rem] leading-relaxed text-ink">{children}</p>;
}

function Table({ head, rows, align, compact }: { head: string[]; rows: string[][]; align: ("l" | "r")[]; compact?: boolean }) {
  return (
    <div className="mt-6 overflow-x-auto rounded-2xl border border-hairline">
      <table className="w-full min-w-[520px] text-[0.84rem]">
        <thead>
          <tr className="border-b border-hairline text-ink-faint">
            {head.map((h, i) => <th key={h} className={`px-4 py-2.5 font-normal ${align[i] === "r" ? "text-right" : "text-left"}`}>{h}</th>)}
          </tr>
        </thead>
        <tbody>
          {rows.map((r, ri) => (
            <tr key={ri} className="border-b border-hairline last:border-0">
              {r.map((c, i) => (
                <td key={i} className={`px-4 ${compact ? "py-1.5" : "py-2.5"} ${align[i] === "r" ? "text-right font-mono text-[0.8rem]" : "text-left"} ${i === 0 ? "text-ink" : "text-ink-soft"}`}>{c}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
